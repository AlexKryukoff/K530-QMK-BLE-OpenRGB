// Подключение k530_spi0_isr() к реальному вектору прерывания.
//
// Вектор подтверждён из sn32_registry.h (ChibiOS-Contrib, семейство
// SN32F240B/SN32F248BF):
//     #define SN32_SPI0_HANDLER   Vector58
//     #define SN32_SPI0_NUMBER    SPI0_IRQn
// Это НЕЗАВИСИМО совпало с найденным ранее вручную в Ghidra адресом
// 0x58 в таблице векторов = IRQ6 = FUN_00009B2E — то есть весь ранее
// реконструированный протокол (раздел 3) подтверждён ещё раз, теперь и
// со стороны официального заголовка платформы, а не только дизассемблера.
//
// OSAL_IRQ_HANDLER — стандартный ChibiOS-макрос: определяет функцию с ABI,
// которого ожидает таблица векторов, и подставляет её вместо weak-заглушки
