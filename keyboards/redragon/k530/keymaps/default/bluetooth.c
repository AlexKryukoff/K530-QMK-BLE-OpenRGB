// сборке через SRC в rules.mk.
OSAL_IRQ_HANDLER(SN32_SPI0_HANDLER) {
    OSAL_IRQ_PROLOGUE();
    k530_spi0_isr();
    OSAL_IRQ_EPILOGUE();
}
