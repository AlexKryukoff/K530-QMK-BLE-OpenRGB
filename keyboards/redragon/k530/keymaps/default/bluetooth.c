    // ЭТОТ вывод (не на "RX frame bytes" выше) в поисках истинного периода
    // повторения "A7 00 00 00 02 FF 00 64" — если период окажется, скажем,
    // ровно 8 или 9 байт, а не 21 — это прямое подтверждение третьей
