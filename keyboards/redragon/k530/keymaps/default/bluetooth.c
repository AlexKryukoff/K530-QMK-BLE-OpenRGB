// ----------------------------------------------------------------------
// Тумблер 1: BT on/off — P1.13 (GPIO1, бит 13)
// Подтверждено измерением: тумблер замыкает линию на GND.
//   бит13 == 0  ->  BT ВКЛЮЧЕН   (mode = 2)
//   бит13 == 1  ->  BT ВЫКЛЮЧЕН  (USB, mode = 1)
// В разомкнутом состоянии линия подтянута резистором к высокому уровню
// (физика подтверждена; программная подтяжка PU в MODE-регистре, если она
// нужна, НЕ была найдена явно в дизассемблере — возможно, подтяжка чисто
// аппаратная, внешним резистором на плате, тогда программно ничего
// настраивать не нужно, кроме самого MODE=вход).
//
// Debounce-паттерн перенесён по аналогии с уже найденным в дизассемблере для
// GPIO0.бит6 (см. отчёт, раунд 6/7: два счётчика, порог 16 итераций вызова).
// ----------------------------------------------------------------------
#define K530_BT_TOGGLE_PIN 13u
#define K530_BT_DEBOUNCE_THRESHOLD 16u
#define K530_HOST_SLOT_SETTLE_POLLS 150u  // selector must REST this many polls before we act (kills sweep-through of slot 2)

static uint8_t k530_bt_toggle_debounce_hi = 0; // счётчик "линия HIGH стабильно"
static uint8_t k530_bt_toggle_debounce_lo = 0; // счётчик "линия LOW стабильно"
static bool    k530_bt_enabled_stable = false;  // дебаунсенное состояние: true = BT включен
static bool    k530_bt_enabled_prev   = false;  // для детекта смены состояния

// Вызывать периодически (например, из bluetooth_task() или matrix_scan_user()).
// Возвращает true, если СТАБИЛЬНОЕ состояние изменилось с прошлого вызова
// (удобно, чтобы среагировать один раз на переключение тумблера).
static bool k530_poll_bt_toggle(void) {
    uint8_t pin_level = (GPIO_REG_DATA(K530_GPIO1_BASE) >> K530_BT_TOGGLE_PIN) & 1u;

    if (pin_level == 1u) {
        // линия HIGH -> тумблер разомкнут -> BT выключен (mode=1)
        k530_bt_toggle_debounce_lo = 0;
        if (k530_bt_toggle_debounce_hi > K530_BT_DEBOUNCE_THRESHOLD) {
            k530_bt_enabled_stable = false;
        } else {
            k530_bt_toggle_debounce_hi++;
        }
    } else {
        // линия LOW -> тумблер замкнут на GND -> BT включен (mode=2)
        k530_bt_toggle_debounce_hi = 0;
        if (k530_bt_toggle_debounce_lo > K530_BT_DEBOUNCE_THRESHOLD) {
            k530_bt_enabled_stable = true;
        } else {
            k530_bt_toggle_debounce_lo++;
        }
    }

    bool changed = (k530_bt_enabled_stable != k530_bt_enabled_prev);
    k530_bt_enabled_prev = k530_bt_enabled_stable;
    return changed;
}

