// ============================================================================
// 4. ФОРМАТ КАДРА (подтверждено реверс-инжинирингом, раунды 4/7)
// ============================================================================
//
// 21 байт:
//   [0]      команда (0xA1 = обычный 6-key HID-отчёт — единственное, что
//             реализуем на этом этапе; NKRO и прочие команды 0xA2-0xA9 —
//             следующий этап)
//   [1]      "mode" — зависит от положения физического тумблера BT on/off
//             (P1.13, см. раздел 2Б). Подтверждено измерением, вычисляется
//             динамически в k530_build_keyboard_frame() ниже.
//   [2]      длина полезной нагрузки (в оригинале для 6-key отчёта = 8)
//   [3..19]  полезная нагрузка (17 байт, для 6-key используются первые 8:
//             [3]=modifier, [4]=reserved(0x00), [5..10]=6 keycodes,
//             [11..19]=не используются для этой команды, заполняем ��улями)
//   [20]     чек-сумма = (сумма байт [0..19]) & 0xFF

// (константы K530_FRAME_LEN / K530_CMD_KEYBOARD_6KEY вынесены в начало
//  файла — см. блок констант перед разделом 2)

static uint8_t k530_checksum(const uint8_t *frame, uint8_t len_without_checksum) {
    uint8_t sum = 0;
    for (uint8_t i = 0; i < len_without_checksum; i++) {
        sum += frame[i];
    }
    return sum;
}

// Собирает 21-байтный кадр из стандартного QMK report_keyboard_t (6KRO).
// report_keyboard_t в QMK для 6KRO обычно содержит:
//   report->mods       — байт модификаторов
//   report->keys[0..5] — 6 keycodes
// (Если ваш форк QMK использует другую структуру report_keyboard_t —
//  ПРОВЕРЬТЕ поля перед использованием, это не универсально между версиями.)
static void k530_build_keyboard_frame(const report_keyboard_t *report, uint8_t out[K530_FRAME_LEN]) {
    memset(out, 0, K530_FRAME_LEN);

    out[0] = K530_CMD_KEYBOARD_6KEY;
    // Раньше здесь была жёстко зашитая константа K530_MODE_BYTE_DEFAULT.
    // Теперь, когда положение физического тумблера BT on/off реально
    // читается (P1.13, см. раздел 2Б), используем подтверждённую полярность:
    // BT включен (бит13==0) -> mode=2, BT выключен (бит13==1) -> mode=1.
    // (Функция bluetooth_send_keyboard() и так не вызывает сборку кадра,
    // если BT физически выключен — но оставляем корректный байт mode и
    // здесь, на случай прямого вызова k530_build_keyboard_frame() в тестах.)
    out[1] = k530_bt_enabled_stable ? 0x02u : 0x01u;
    out[2] = 8; // длина полезной нагрузки для 6-key отчёта (подтверждено дампом)

    out[3] = report->mods;   // byte modifier
    out[4] = 0x00;             // reserved — в оригинале почти всегда 0

#if defined(NKRO_ENABLE)
    // TODO(этап 2): если сборка компилируется с NKRO, здесь нужно ветвление
    // на команду 0xA3 (или соответствующую) с полным битмапом — см. отчёт,
    // буфер NKRO 0x2000025E, 32 байта. Не реализовано в этом черновике —
    // сознательно откладываем на второй этап, как договорились.
#endif

    for (uint8_t i = 0; i < 6; i++) {
        out[5 + i] = report->keys[i];
    }

    // байты [11..37] остаются нулями (memset выше)
    // ВАЖНО: реальный кадр на шине — 39 байт, чек-сумма на смещении 38
    // (running-sum bytes[0..37] & 0xFF). Подтверждено дизассемблером стоковой
    // прошивки: ISR SPI0 (IRQ6, 0x9D06) накапливает до индекса 0x27=39 и
    // сверяет байт[38]; модуль читает ровно столько же байт с нашей линии
    // MISO из TX-таблицы 0x20000B38. При длине 21 байт чек-сумма попадала на
    // позицию 20, а на позиции 38 модуль видел 0x00 -> отвергал кадр.
    out[38] = k530_checksum(out, 38);
}

// ============================================================================
// 4Б. УПРАВЛЯЮЩИЙ КАДР ВКЛ/ВЫКЛ BT (команда 0xA5, стоковый построитель 0x02AC)
// ============================================================================
// Ключевой вывод реверса стока (2RCData4000.bin): выключение BT
// НЕ через питание/GPIO. Главный чип шлёт модулю по SPI
// управляющий кадр, где состояние линка — байт[7] (RAM 0x200000BB):
//   0x01 = ON, 0x02 = OFF.  Пока кадр не отправлен, модуль активен
// и продолжает рекламу. Формат (39 байт), декодирован @0x02AC:
//   [0]=0xA5 cmd; [1]=хост №2; [2]=0x05 (B6=длина payload); [3]=слот 0x02/0x00;
//   [4]=0x0A; [5]=0x19; [6]=0x00; [7]=линк 0x01/0x02; [8..37]=0; [38]=cs.
#define K530_CMD_BT_CONTROL 0xA5u

static void k530_build_control_frame(bool enabled, uint8_t out[K530_FRAME_LEN]) {
    // === STOCK A5 automaton (disasm 0x0A64..0x0AE2 + serializer 0x02E4..0x0334) ===
    // A5 frame: [0]=0xA5,[1]=mode,[2]=B6,[3]=C2,[4]=0x0A,[5]=0x19,[6]=C3,[7]=BB,[8..37]=0,[38]=cksum.
    //   ADVERTISE/CONNECT (phys ON):  byte[7]=BB=0x02, byte[3]=C2=0x00
    //   SILENT/DISCONNECT (phys OFF): byte[7]=BB=0x01, byte[3]=C2=0x03
    // FIX: byte[3] previously held host_idx (0..2). For slot 1 the OFF frame was
    // [3]=0x00,[7]=0x01, which does NOT match stock (C2 must be 0x03) -> the module
    // never dropped the link. Host number is a SEPARATE 0xA6 command, not this field.
    memset(out, 0, K530_FRAME_LEN);
    out[0] = K530_CMD_BT_CONTROL;      // 0xA5
    out[1] = 0x02u;                    // mode (stock: 0x40046000 bit14; link-agnostic)
    out[2] = 0x05u;                    // B6 = payload length ([3..7] = 5 bytes)
    out[3] = enabled ? 0x00u : 0x03u;  // C2: 0x00 advertise / 0x03 disconnect (STOCK)
    out[4] = 0x0Au;
    out[5] = 0x19u;
    out[6] = 0x00u;                    // C3 (stock zeroes it after building the frame)
    out[7] = enabled ? 0x02u : 0x01u;  // BB: 0x02 advertise / 0x01 stop/reconnect (STOCK)
    out[38] = k530_checksum(out, 38);
}

// Передать модулю команду вкл/выкл линка. Заставляет сам модуль
// разорвать соединение и прекратить рекламу при OFF.
// Точный порт стокового строба 0x043C: P0.1 ПРИНУДИТЕЛЬНО в output, затем
// импульс HIGH -> (кратко) -> LOW -> длинная выдержка (сток: delay 100).
// В отличие от k530_bt_pulse_ready() гарантируем направление пина
// (SPI0-инициализация могла оставить P0.1 не как GPIO-выход) и даём паузу
// после строба, чтобы модуль успел инициировать чтение управляющего кадра.
static void k530_bt_strobe_control(void) {
    GPIO_REG_MODE(K530_GPIO0_BASE) |= (1u << K530_BT_READY_PIN);  // P0.1 = output
    k530_gpio_set(K530_GPIO0_BASE, K530_BT_READY_PIN);           // P0.1 HIGH
    wait_us(K530_BT_STROBE_DELAY_US);
    k530_gpio_clear(K530_GPIO0_BASE, K530_BT_READY_PIN);         // P0.1 LOW
    wait_us(100u * K530_BT_STROBE_DELAY_US);                     // выдержка (сток: delay 100)
}

// Передать модулю команду вкл/выкл линка. Заставляет сам модуль
// разорвать соединени�� и прекратить рекламу при OFF.
static void k530_send_bt_control(bool enabled) {
    uint8_t frame[K530_FRAME_LEN];
    k530_build_control_frame(enabled, frame);
    K530_BT_LOG_FRAME("TX BT control frame", frame, K530_FRAME_LEN);
    // Держим управляющий кадр в TX-буфере и стробим НЕСКОЛЬКО раз,
    // чтобы модуль гарантированно забрал его на одном из своих опросов
    // (в стоке кадр защищён флагом-гейтом bit5; здесь имитируем повторами).
    // STOCK-FAITHFUL: reinit SPI0 (FUN_00009b90) immediately before the frame,
    // then load + single strobe (stock sends once via the gate, not in a loop).
    k530_spi0_reinit();
    k530_spi0_load_tx_buffer(frame, K530_FRAME_LEN);
    k530_bt_strobe_control();
}

// === Остановка рекламы (команда 0x00) ===
// ЛОГ ДОКАЗАЛ: реклама автономна — отключение SPI0 её НЕ гасит
// (IRQ-счётчик замирал, но модуль вещал). Сток шлёт по ЖИВОМУ линку
// к��др с командой 0x00 в состоянии BB==2 (advertise) — дизасм 0x86FE..0x8712.
#define K530_CMD_BT_STOP 0x00u

// Период повторной отправки 0x00 в положении OFF (housekeeping-таск).
#define K530_BT_OFF_STOP_PERIOD 200u

// Stock inserts real watchdog-fed delays (BL 0x025A, args 0x14/0x28) after a
// 0xA6 host-switch before doing anything else. Without a settle the module
// has not committed the new host yet, so the immediately-following 0xA5
// re-advertises on the PREVIOUS host -> displayed name lags one step behind
// the physical 1/2/3 selector. Give the module time to switch hosts.
#define K530_BT_HOST_SWITCH_SETTLE_MS 30u

// AUTO OFF->switch->ON cycle timings for the 1/2/3 host selector. The module
// will NOT switch host while a link is up (A7 byte[4] >= 0x02), so on a slot
// change we disconnect, WAIT until the module actually drops (polling A7
// byte[4]), then switch host + re-advertise. Timings are deliberately generous
// (user preference) -- a brief link drop while switching is fine.
#define K530_BT_HOST_SWITCH_DROP_TIMEOUT_MS 3000u  // max wait for FULL disconnect (A7==0x00)
#define K530_BT_HOST_SWITCH_REKICK_MS        250u   // re-send disconnect every N ms (gentle, let module answer)
#define K530_BT_HOST_SWITCH_PRE_MS          150u   // settle after disconnect, before 0xA6
#define K530_BT_HOST_SWITCH_POST_MS         200u   // settle after 0xA6, before advertise

// === Смена активного хоста draconic-1/2/3 (команда 0xA6) ===
// Реверс стока: обработчик смены селектора (0x56D6) при изменении хоста
// шлёт ОТДЕЛЬНУЮ команду 0xA6 (не 0xA5!). Сборщик 0x02AC для 0xA6
// (case 0x0336) кладёт: TX[3]=BE(=0x02), TX[4]=номер хоста (в стоке из 0x20000125).
// byte[1]/byte[2] общие для всех команд (P1.14 -> 0x02; B6 -> 0x05).
#define K530_CMD_BT_HOST_SWITCH 0xA6u

static void k530_build_host_switch_frame(uint8_t out[K530_FRAME_LEN]) {
    // 0-based индекс: draconic-1 -> 0, draconic-2 -> 1, draconic-3 -> 2.
    // Если окажется сдвиг на 1 — поправим по логу (host_idx +/- 1).
    uint8_t host_idx = (k530_host_slot_stable >= K530_HOST_SLOT_1 &&
                        k530_host_slot_stable <= K530_HOST_SLOT_3)
                           ? (uint8_t)((uint8_t)k530_host_slot_stable - 1u) : 0u;
    memset(out, 0, K530_FRAME_LEN);
    out[0] = K530_CMD_BT_HOST_SWITCH;  // 0xA6
    out[1] = 0x02u;                    // как в 0xA5 (P1.14-канал)
    out[2] = 0x05u;                    // B6 (общий для команд)
    out[3] = 0x02u;                    // BE
    out[4] = host_idx;                 // *** НОМЕР ХОСТА (draconic-N) ***
    out[38] = k530_checksum(out, 38);
}

// STOCK PREP @0x043C -- the host-switch-specific "primer" strobe. This is the
// ONLY extra thing stock does for 0xA6 that it never does for the 0xA5 control
// path: hold the P0.1 ready line HIGH for 1ms, then LOW for 100ms. That 100ms
// LOW is the brief backlight-off the user sees on every 1/2/3 flick -- an
// attention/re-sync signal that primes the BT module to accept the incoming
// host switch. Without it the module only honored the 0xA6 intermittently.
static void k530_bt_prep_host_switch(void) {
    GPIO_REG_BSET(K530_GPIO0_BASE) = (1u << K530_BT_READY_PIN);   // P0.1 HIGH
    GPIO_REG_MODE(K530_GPIO0_BASE) =
        (GPIO_REG_MODE(K530_GPIO0_BASE) & ~(1u << K530_BT_READY_PIN))
        | (1u << K530_BT_READY_PIN);                              // P0.1 OUTPUT
    GPIO_REG_BSET(K530_GPIO0_BASE) = (1u << K530_BT_READY_PIN);   // P0.1 HIGH
    wait_ms(1u);                                                  // stock BL 0x025A(1)
    GPIO_REG_BCLR(K530_GPIO0_BASE) = (1u << K530_BT_READY_PIN);   // P0.1 LOW
    wait_ms(100u);                                                // stock BL 0x025A(0x64) -> backlight blink
}

static void k530_send_bt_host_switch(void) {
    uint8_t frame[K530_FRAME_LEN];
    k530_build_host_switch_frame(frame);
    K530_BT_LOG_FRAME("TX BT host-switch frame", frame, K530_FRAME_LEN);
    // === STOCK-FAITHFUL host switch (disasm 0x56D6) ===
    // Stock does NOT disconnect, NOT wait for A7==0x00, NOT cycle OFF/ON, and
    // sends NO 0xA5 afterwards. It runs the PREP primer strobe, then clocks
    // exactly ONE 0xA6 frame; the module switches host and advertises the new
    // name (draconic-N) by itself. Replicate 1:1.
    k530_bt_prep_host_switch();                 // 0x043C primer (P0.1 1ms HIGH / 100ms LOW)
    k530_spi0_reinit();                         // fresh SPI0 slave state before the frame
    k530_spi0_load_tx_buffer(frame, K530_FRAME_LEN);
    wait_ms(20u);                               // stock BL 0x025A(0x14): 20ms settle after frame prep, before send
    k530_bt_strobe_control();                   // normal 10us send strobe (stock send-tail)
    wait_ms(40u);                               // stock BL 0x025A(0x28): 40ms hold after send, before returning
}

// Временный флаг: пока добиваем ON/OFF по стоку, НЕ шлём 0xA6-переключение
// хоста (чтобы тесты тумблера были чистыми). Вернём в true, когда
// ON/OFF станет стабильным.
// ENABLED: ON/OFF is stable and confirmed by logs. Host/name switching by the
// 1/2/3 selector now sends the stock 0xA6 command (A6 02 05 02 <host_idx>...)
// on ON-transition and on any host-slot change while ON. host_idx is 0-based
// (draconic-1->0, draconic-2->1, draconic-3->2); adjust in
// k530_build_host_switch_frame if the log shows an off-by-one.
static const bool k530_bt_host_switch_enabled = true;

// NOTE (CORRECTED): OFF is done by an SPI FRAME, not by disabling SPI0.
// Hardware proof: only 5 SPI wires + P0.1 strobe, no power/reset line, yet
// stock instantly drops the iPhone link on OFF -> disconnect MUST be a frame.
// Stock sends A5 with C2=0x03 / BB=0x01 via the gated serializer (0x02AC) +
// P0.1 strobe. Disabling MCU SPI0 does NOT silence the autonomous radio
// (log: A7 status frames kept coming at OFF). See k530_send_bt_control().


// ============================================================================
// 4В. СБРОС СОПРЯЖЕНИЯ / re-pair (Fn2+ESC, удержание 3 сек — как в стоке)
// ============================================================================
// НАЙДЕНО ПОЛНЫМ РЕВЕРСОМ СТОКА (раунд 14, трассировка жеста Fn2+ESC):
//   Fn2+ESC (базовый ESC = HID 0x29, таблица Fn2-комбо 0xCD50, entry idx4)
//   -> FSM action 0x2C -> обработчик 0x4C82. По фронту нажатия он НЕ шлёт кадр,
//   а взводит bit6 (0x40) в 0x20000008 и обнуляет счётчик [0x200000B7].
//   Периодический BT-планировщик (~0x0940) пока bit6 взведён ИНКРЕМЕНТИРУЕТ
//   [0x200000B7] по тикам; когда счётчик достигает 0x37 (=55, это и есть ~3 сек)
//   планировщик (0x0B66..0x0BA6) шлёт кадр:
//        [0x200000BC]=0xA6 (команда), [0x200000BE]=0x01 (!!!), кадр -> BL 0x02AC.
//
// КЛЮЧЕВОЕ: это 0xA6, НО с байтом[3]=0x01. Обычное переключение хоста (0x56D6)
// и весь остальной код шлют 0xA6 с байтом[3]=0x02. Значение [0x200000BE]=0x01
// пишется РОВНО В ОДНОМ месте — на пути 3-сек удержания Fn2+ESC (0x0B7E). Это и
// есть маркер "забыть бонд". Раньше мы слали только вариант 0x02 (смена хоста) —
// поэтому бонд не чистился. ПОДТВЕРЖДЕНО НА ЖЕЛЕЗЕ: команда УНИВЕРСАЛЬНА —
// сбрасывает бонд на ЛЮБОМ слоте (маркер 0x01 един; байт[4] просто следует за
// текущим хостом, как в стоке). Кадр:
//   byte[0]=0xA6, byte[1]=mode(0x02), byte[2]=B6(0x05),
//   byte[3]=0x01  <-- МАРКЕР СБРОСА БОНДА,
//   byte[4]=номер текущего хоста (0-based: draconic-1->0 .. draconic-3->2),
//   byte[5..37]=0, byte[38]=checksum.
// Отправляем стоково-точно: тот же primer-строб 0x043C, что и у смены хоста.
#define K530_CMD_BT_UNPAIR_MARKER 0x01u   // [0x200000BE]=1 -> сброс бонда (vs 0x02 = смена хоста)

static void k530_build_unpair_frame(uint8_t out[K530_FRAME_LEN]) {
    // Номер ТЕКУЩЕГО хоста (тот, чей бонд чистим), 0-based — как в стоковом A6.
    uint8_t host_idx = (k530_host_slot_stable >= K530_HOST_SLOT_1 &&
                        k530_host_slot_stable <= K530_HOST_SLOT_3)
                           ? (uint8_t)((uint8_t)k530_host_slot_stable - 1u) : 0u;
    memset(out, 0, K530_FRAME_LEN);
    out[0] = K530_CMD_BT_HOST_SWITCH;      // 0xA6 (та же команда, что и смена хоста)
    out[1] = 0x02u;                        // mode (P1.14-канал; как во всех кадрах)
    out[2] = 0x05u;                        // B6 payload length
    out[3] = K530_CMD_BT_UNPAIR_MARKER;    // 0x01 = СБРОС БОНДА (стоковое 0x0B7E)
    out[4] = host_idx;                     // текущий хост draconic-N (0-based)
    out[38] = k530_checksum(out, 38);
}

void k530_send_bt_unpair(void) {
    if (!k530_bt_enabled_stable || !k530_spi0_slave_ready) return;

    uint8_t frame[K530_FRAME_LEN];
    k530_build_unpair_frame(frame);
    K530_BT_LOG_FRAME("BT UNPAIR: A6 marker=0x01 (стоковый сброс бонда)", frame, K530_FRAME_LEN);

    // Стоково-точная выдача A6 (как в k530_send_bt_host_switch): primer-строб
    // 0x043C -> reinit SPI0 -> загрузка кадра -> выдержка -> строб -> выдержка.
    k530_bt_prep_host_switch();                 // 0x043C primer (P0.1 1мс HIGH / 100мс LOW)
    k530_spi0_reinit();
    k530_spi0_load_tx_buffer(frame, K530_FRAME_LEN);
    wait_ms(20u);                               // стоковая выдержка перед отправкой
    k530_bt_strobe_control();
    wait_ms(40u);                               // стоковая выдержка после отправки
}


