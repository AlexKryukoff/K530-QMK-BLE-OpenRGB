// ============================================================================
// 5Б. ОТЛАДКА НА РЕАЛЬНОМ ЖЕЛЕЗЕ БЕЗ ЛОГИЧЕСКОГО АНАЛИЗАТОРА
// ============================================================================
// Печать прямо из k530_spi0_isr() НЕ ДЕЛАЕМ — прерывание должно быть быстрым
// (мастер клокует байты с фиксированным таймингом, задержка в обработчике
// может привести к рассинхронизации побайтового обмена). Вместо этого ISR
// только копирует нужные данные в простую volatile-структуру-снимок, а сама
// печать (uprintf/dprintf) происходит из bluetooth_task(), которая
// вызывается из основного цикла QMK, не из прерывания.
//
// Использование: добавьте в rules.mk вашей клавиатуры
//     CONSOLE_ENABLE = yes
