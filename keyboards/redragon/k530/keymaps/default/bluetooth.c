// ----------------------------------------------------------------------
// Тумблер 2: выбор хоста/слота сопряжения (1/2/3) — P0.6 + P0.7
//
// Физическая схема (подтверждено прозвонкой): переключатель на 4 контакта
// (GND, 3V, и два вывода на P0.6/P0.7):
//   Позиция 1: P0.6 = 3В (питание),        P0.7 = не подключён
//   Позиция 2: P0.6 и P0.7 ЗАМКНУТЫ друг на друга, оба "висят в воздухе"
//   Позиция 3: P0.6 = земля (GND),          P0.7 = не подключён
//
// P0.7 сам по себе не даёт стабильного сигнала (висит в воздухе в позициях
// 1 и 3) — читать его как обычный вход бессмысленно. Найденный в дизассемблере
// механизм (см. отчёт, функция ~0x5414, блоки 0x5430-0x544C и 0x5620-0x565A):
// прошивка ДВАЖДЫ кратковременно настраивает P0.7 как ВЫХОД и поочерёдно
// выставляет на нём HIGH, затем LOW, каждый раз считывая P0.6 сразу после:
//
//   1) MODE(P0.7) = output; DATA(P0.7) = HIGH; читать DATA(P0.6)  -> result_hi
//   2) MODE(P0.7) = output; DATA(P0.7) = LOW;  читать DATA(P0.6)  -> result_lo
//
// Дословно из дизассемблера подтверждён САМ этот двухфазный механизм
// (drive-HIGH-и-читать / drive-LOW-и-читать) — оба блока с манипуляцией
// MODE(+0x04) и DATA(+0x00) регистра GPIO0 для бита 0x80 (P0.7), сразу
// после которых идёт извлечение бита 6. НЕ найден байт-в-байт код,
// КОМБИНИРУЮЩИЙ result_hi/result_lo в итоговую позицию 1/2/3 — то, что
// ниже, это логическая реконструкция ПО ФИЗИКЕ, которую вы измерили,
// а не дословный перенос конкретных констант из RAM (0x20000008 бит22/23
// в оригинале, судя по всему, используются для чего-то похожего, но
// итоговый "switch по трём позициям" не был локализован явно):
//
//   result_hi==1 && result_lo==1  -> P0.6 не следует за P0.7 => позиция 1 (3V, фиксированный HIGH)
//   result_hi==0 && result_lo==0  -> P0.6 не следует за P0.7 => позиция 3 (GND, фиксированный LOW)
//   result_hi==1 && result_lo==0  -> P0.6 СЛЕДУЕТ за P0.7    => позиция 2 (замкнуты между собой)
//   (result_hi==0 && result_lo==1 — не должно происходить при исправном
//    железе; в коде трактуется как "неопределено", оставляем прошлое
//    стабильное значение)
// ----------------------------------------------------------------------
#define K530_HOST_SLOT_PIN_SENSE  6u   // P0.6 — считываемая линия
#define K530_HOST_SLOT_PIN_DRIVE  7u   // P0.7 — кратковременно настраивается как выход

typedef enum {
    K530_HOST_SLOT_1 = 1,
    K530_HOST_SLOT_2 = 2,
    K530_HOST_SLOT_3 = 3,
    K530_HOST_SLOT_UNKNOWN = 0,
} k530_host_slot_t;

// ВАЖНО: k530_host_slot_stable сейчас только ОПРАШИВАЕТСЯ (debounce,
// хранение стабильного значения) — но НИГДЕ не используется при сборке
// исходящего кадра в k530_build_keyboard_frame() ниже и не влияет на TX[1]
// (mode) или другие поля. В оригинальной прошивке связь между выбранным
// слотом хоста и содержимым кадра не была прослежена в этой сессии
// реверс-инжиниринга (см. отчёт, раунд 7-8 — команда 0xA7 предположительно
// связана с "переключением хоста", но её точная связь с P0.6/P0.7 не
// подтверждена). Для минимальной 6-key версии драйвера это не блокирует
// работу (клавиатура будет слать отчёты независимо от выбранного слота),
// но если нужна поддержка нескольких сопряжённых устройств — здесь нужно
// доработать протокол (вероятно, отправка команды 0xA7 с номером слота при
// смене k530_poll_host_slot(), либо иной, пока не найденный механизм).
static k530_host_slot_t k530_host_slot_stable = K530_HOST_SLOT_UNKNOWN;
static uint8_t k530_host_slot_debounce_counter = 0;

// Кратковременно настраивает P0.7 как выход с заданным уровнем, читает P0.6,
// затем возвращает P0.7 обратно в режим входа (чтобы не мешать позиции 1/3,
// где P0.7 физически не подключён — держать его постоянно в output могло бы
// создать конфликт, если он всё же к чему-то подключён в других ревизиях платы).
static uint8_t k530_read_p06_after_driving_p07(bool drive_high) {
    // Настроить P0.7 как выход (бит7 регистра MODE = 1, по аналогии с уже
    // подтверждённым паттерном из дизассемблера)
    GPIO_REG_MODE(K530_GPIO0_BASE) = (GPIO_REG_MODE(K530_GPIO0_BASE) & ~(1u << K530_HOST_SLOT_PIN_DRIVE))
                                       | (1u << K530_HOST_SLOT_PIN_DRIVE);
    if (drive_high) {
        GPIO_REG_DATA(K530_GPIO0_BASE) = (GPIO_REG_DATA(K530_GPIO0_BASE) & ~(1u << K530_HOST_SLOT_PIN_DRIVE))
                                           | (1u << K530_HOST_SLOT_PIN_DRIVE);
    } else {
        GPIO_REG_DATA(K530_GPIO0_BASE) = (GPIO_REG_DATA(K530_GPIO0_BASE) & ~(1u << K530_HOST_SLOT_PIN_DRIVE));
    }

    // TODO/CONFIRM: в оригинале между настройкой строба и чтением, судя по
    // всему, нет отдельной задержки (переход сразу к следующей инструкции) —
    // возможно, полагается на естественную задержку из-за самих
    // read-modify-write операций. Если на реальном железе понадобится время
    // на "устаканивание" уровня — добавьте здесь короткий wait_us(1..5).

    uint8_t p06 = (GPIO_REG_DATA(K530_GPIO0_BASE) >> K530_HOST_SLOT_PIN_SENSE) & 1u;

    // Вернуть P0.7 обратно в режим входа (осторожный выбор, не подтверждён
    // дословно дизассемблером — оригинал, возможно, просто оставляет P0.7
    // в режиме output между опросами; если увидите на реальном железе
    // конфликт/нестабильность — попробуйте убрать этот возврат в input).
    GPIO_REG_MODE(K530_GPIO0_BASE) = (GPIO_REG_MODE(K530_GPIO0_BASE) & ~(1u << K530_HOST_SLOT_PIN_DRIVE));

    return p06;
}

// Вызывать периодически. Возвращает true, если стабильная позиция изменилась.
static bool k530_poll_host_slot(void) {
    uint8_t result_hi = k530_read_p06_after_driving_p07(true);
    uint8_t result_lo = k530_read_p06_after_driving_p07(false);

    k530_host_slot_t detected;
    if (result_hi == 1u && result_lo == 1u) {
        detected = K530_HOST_SLOT_1;
    } else if (result_hi == 0u && result_lo == 0u) {
        detected = K530_HOST_SLOT_3;
    } else if (result_hi == 1u && result_lo == 0u) {
        detected = K530_HOST_SLOT_2;
    } else {
        // "невозможная" комбинация (0,1) — считаем шумом/неисправностью,
        // не меняем стабильное состояние на этом опросе.
        detected = k530_host_slot_stable;
    }

    bool changed = false;
    if (detected == k530_host_slot_stable) {
        k530_host_slot_debounce_counter = 0;
    } else {
        k530_host_slot_debounce_counter++;
        if (k530_host_slot_debounce_counter > K530_BT_DEBOUNCE_THRESHOLD) {
            k530_host_slot_stable = detected;
            k530_host_slot_debounce_counter = 0;
            changed = true;
        }
    }
    return changed;
}

// ============================================================================
// 3. АППАРАТНЫЙ УРОВЕНЬ — SPI0 SLAVE (перенесено дословно из FUN_00009B2E)
// ============================================================================
// PAR2801QN-GHVC работает как SPI MASTER, значит главный MCU (VS11K09A-1) —
// SPI SLAVE. Обмен полнодуплексный побайтовый: на КАЖДЫЙ входящий байт от
// мастера slave обязан ОДНОВРЕМЕННО выдать байт ответа (сдвиговый регистр).
//
// Карта регистров SPI0 подтверждена ДВАЖДЫ независимо: сначала через SVD-Loader
// (другая модель, работавшая с этим же дампом в Ghidra), и в этой сессии —
// собственным дословным дизассемблированием FUN_00009B2E:
//   база:            0x4001C000
//   RIS (offset+0x14): Raw Interrupt Status — бит 2 (маска 0x4) = "байт принят"
//   IC  (offset+0x18): Interrupt Clear — write-1-to-clear того же бита 2
//   DATA(offset+0x1C): регистр данных — чтение = принятый байт, запись = байт
//                       на отправку СЛЕДУЮЩИМ тактом
//
// CTRL0/CTRL1/CLKDIV (режим/скорость SPI) в этой ISR не используются —
// настраиваются один раз при инициализации в ДРУГОМ месте прошивки, которое
// в этой сессии реверс-инжиниринга НЕ было найдено. ЭТО ОСТАЁТСЯ TODO.

#define K530_SPI0_BASE 0x4001C000u
#define SPI0_REG_RIS   (*(volatile uint32_t *)(K530_SPI0_BASE + 0x14))
#define SPI0_REG_IC    (*(volatile uint32_t *)(K530_SPI0_BASE + 0x18))
#define SPI0_REG_DATA  (*(volatile uint32_t *)(K530_SPI0_BASE + 0x1C))
#define SPI0_RIS_RX_BIT 0x4u
// RXTOIF/RXTOIE/RXTOIC — бит 1, ПОДТВЕРЖДЕНО даташитом Sonix SN32F248B
// (стр. 111): "RXTO occurs when the RX FIFO is not empty, and has not
// been read for a time-out period (32×SPIn_PCLK)". Использовалась как
// диагностика для проверки гипотезы "триггер границы кадра" — ГИПОТЕЗА
// ЗАКРЫТА эмпирически: событие срабатывает практически непрерывно и почти
// всегда посреди приёма (порог ≈0.67 мкс при HCLK=48МГц, физически не
// успевает дождаться следующего байта нормального потока). Диагностический
// код по ней убран из ISR; константа оставлена только для справки/на
// случай, если понадобится другая проверка этого бита в будущем.
#define SPI0_RIS_RXTO_BIT 0x2u

// ----------------------------------------------------------------------
// Регистры SPI0, дополнительно подтверждённые в этом раунде дословным
// дизассемблированием FUN_00009980 / FUN_000099AC / FUN_000099B8 / FUN_00009A44:
//   CTRL0 (offset+0x00): бит0=enable периферии, биты[7:6], бит1, бит2, бит3,
//                        биты[11:8]=режим/делитель(?), бит18 — назначение
//                        отдельных битов кроме bit0(enable) НЕ расшифровано
//                        по смыслу, только по факту "какие биты трогает
//                        оригинал" — переносим значения как есть, без
//                        досочинённой семантики.
//   IE    (offset+0x10): Interrupt Enable (0=выкл всё, 4=разрешить RX-бит)
//   CLKDIV (offset+0x08) и ещё один рег. (offset+0x0C): доп. регистры
//                        назначение битов не расшифровано, переносим
//                        операции как есть.
//   0x4005E000, бит 12: clock gate (тактирование) SPI0-периферии.
//   NVIC->ISER[0], бит 6: разрешение IRQ6 (подтверждённый вектор SPI0 для
//                        именно этого чипа, VS11K09A-1/SN32F248B).
// ----------------------------------------------------------------------
#define SPI0_REG_CTRL0 (*(volatile uint32_t *)(K530_SPI0_BASE + 0x00))
#define SPI0_REG_IE    (*(volatile uint32_t *)(K530_SPI0_BASE + 0x10))
#define SPI0_REG_CTRL1_REAL (*(volatile uint32_t *)(K530_SPI0_BASE + 0x04)) // настоящий CTRL1 (+0x04)
#define SPI0_REG_CLKDIV (*(volatile uint32_t *)(K530_SPI0_BASE + 0x08))    // это CLKDIV, не CTRL1 (имя было перепутано)
// (offset+0x0C не встретился ни в одной из разобранных SPI0-функций —
//  раньше здесь ошибочно предполагался регистр CTRL1B, но по факту он
//  не используется ни в FUN_99B8, ни где-либо ещё в проверенном коде)

#define K530_CLKGATE_REG (*(volatile uint32_t *)0x4005E000u)
#define K530_NVIC_ISER0  (*(volatile uint32_t *)0xE000E100u)  // Set Enable
#define K530_NVIC_ICPR0  (*(volatile uint32_t *)0xE000E280u)  // Clear Pending
#define K530_SPI0_NVIC_IRQ_BIT 6u

// FUN_00009980 — включить тактирование + базовые биты CTRL0 (enable + 0xC0)
static void k530_spi0_clock_and_basic_enable(void) {
    K530_CLKGATE_REG |= (1u << 12);
    SPI0_REG_CTRL0 = (SPI0_REG_CTRL0 & ~1u) | 1u;
    SPI0_REG_CTRL0 = (SPI0_REG_CTRL0 & ~0xC0u) | 0xC0u;
}

// FUN_000099AC — сбросить все флаги прерываний и разрешить именно RX (бит2).
// (Диагностика RXTOIE была временной и убрана после теста на реальном
// железе — гипотеза "RXTOIF как надёжный триггер границы кадра"
// эмпирически ОПРОВЕРГНУТА: событие срабатывает практически непрерывно и
// почти всегда посреди приёма кадра (was_receiving=true), что напрямую
// подтвердило трактовку "32×PCLK ≈ 0.67 мкс напрямую от HCLK" вместо
// "через делённый CLKDIV spiClock ≈ 4 мкс" — порог физически не успевает
// дождаться следующего байта нормального кадра. См. отчёт, соответствующий
// раунд, для полной истории обеих проверенных и закрытых гипотез.)
static void k530_spi0_clear_flags_and_enable_rx_irq(void) {
    SPI0_REG_IC = 0xFu;   // очистить ВСЕ флаги (не только бит RX)
    SPI0_REG_IE = SPI0_RIS_RX_BIT;   // разрешить только RX-прерывание (как в оригинале)
}

// FUN_000099B8 — полная переинициализация SPI0 (вызывается ПОСЛЕ disable,
// как в оригинале — см. использование в k530_spi0_isr ниже).
// ИСПРАВЛЕНО: изначально функция была ошибочно обрезана по произвольной
// границе окна дизассемблирования (0x9980-0x9a30) — реальный конец FUN_99B8
// на 0x9A42 (там настоящий "pop {pc}"), и в хвосте есть ещё 3 важных шага,
// которые были пропущены в первой версии этого файла:
//   1) ICPR (0xE000E280) — сброс pending-флага IRQ6 ПЕРЕД его разрешением
//   2) ISER (0xE000E100) — собственно разрешение IRQ6 (порядок именно такой:
//      сначала ICPR, потом ISER — иначе возможно паразитное немедленное
//      срабатывание прерывания со старым состоянием)
//   3) повторный вызов FUN_00009980 (k530_spi0_clock_and_basic_enable) —
//      САМЫЙ ПОСЛЕДНИЙ шаг всей функции. Без него после disable()+reinit()
//      бит0 (enable) CTRL0 остаётся в неопределённом состоянии, и SPI0
//      физически не включится обратно после первого кадра.
static void k530_spi0_reinit(void) {
    // ИСПРАВЛЕНО: в оригинале (0x99BA-0x99C8) это ОДНА аппаратная запись —
    // очистка и установка бита 12 происходят в регистре CPU (bics+adds),
    // и в железо пишется только итоговое значение ОДИН раз. Раньше здесь
    // ошибочно было два отдельных volatile-присваивания подряд, что реально
    // гасило тактирование SPI0 и включало его обратно — на реальном железе
    // это могло привести к незапланированному сбросу периферии на каждый
    // вызов reinit(). Правильный перевод — просто гарантированная установка
    // бита в 1, без промежуточного физического сброса:
    K530_CLKGATE_REG |= (1u << 12);

    SPI0_REG_CTRL0 = (SPI0_REG_CTRL0 & ~(0xFu << 8)) | (0x7u << 8);
    SPI0_REG_CTRL0 = (SPI0_REG_CTRL0 & ~0x8u) | 0x8u;
    SPI0_REG_CTRL0 = (SPI0_REG_CTRL0 & ~0x2u);
    SPI0_REG_CTRL0 = (SPI0_REG_CTRL0 & ~0x4u);

    SPI0_REG_CLKDIV = (SPI0_REG_CLKDIV & 0xFFFFFF00u) | 0x2u;
    // ИСПРАВЛЕНО: раньше здесь ошибочно писалось в SPI0_REG_CTRL1B (+0x0C),
    // которого в этой операции не существует. Дословная сверка по количеству
    // str в дизассемблере (0x9A12: str r0,[r1,#4], где r1=0x4001C000 без
    // переинициализации от предыдущего шага) показала: запись "=0" идёт на
    // offset+0x04 — то есть в НАСТОЯЩИЙ CTRL1, а не в +0x0C.
    SPI0_REG_CTRL1_REAL = 0u;

    SPI0_REG_CTRL0 = (SPI0_REG_CTRL0 & ~(1u << 18));

    k530_spi0_clear_flags_and_enable_rx_irq();   // bl 0x99AC

    K530_NVIC_ICPR0 = (1u << K530_SPI0_NVIC_IRQ_BIT);  // сброс pending — ПЕРВЫМ
    K530_NVIC_ISER0 = (1u << K530_SPI0_NVIC_IRQ_BIT);  // разрешение — ВТОРЫМ

    k530_spi0_clock_and_basic_enable();  // bl 0x9980 — ПОСЛЕДНИЙ шаг оригинала!
}

// FUN_00009A44 — полное выключение SPI0 (интерраптов, периферии, тактирования)
static void k530_spi0_disable(void) {
    SPI0_REG_IE = 0u;
    SPI0_REG_CTRL0 = (SPI0_REG_CTRL0 & ~1u);
    K530_CLKGATE_REG = (K530_CLKGATE_REG & ~(1u << 12));
}

// ----------------------------------------------------------------------
// Регистр CFG порта GPIO0 (offset+0x08) — выбор альтернативной функции
// пина, 2-битное поле на каждый пин. Значение поля = 2 включает SPI0 на
// пинах P0.2-P0.5. Подтверждено дословным дизассемблированием (см. блок
// 0x2EF0-0x2F84, часть общей последовательности "пробуждение из сна").
// ----------------------------------------------------------------------
#define GPIO_REG_CFG(base) (*(volatile uint32_t *)((base) + 0x08))

// Настройка P0.2-P0.5 под альтернативную функцию SPI0 (MISO0/MOSI0/SCK0/SEL0).
// Перенесено дословно из прошивки.
static void k530_spi0_pins_to_alt_function(void) {
    // Сначала MODE=0 для этих пинов (значение бита при альтернативной
    // функции в оригинале — "отдать управление CFG", не входное состояние
    // в привычном смысле "plain GPIO input"):
    GPIO_REG_MODE(K530_GPIO0_BASE) &= ~(1u << 2);
    GPIO_REG_MODE(K530_GPIO0_BASE) &= ~(1u << 3);
    GPIO_REG_MODE(K530_GPIO0_BASE) &= ~(1u << 4);
    GPIO_REG_MODE(K530_GPIO0_BASE) &= ~(1u << 5);

    // CFG: 2-битные поля, P0.2=[5:4], P0.3=[7:6], P0.4=[9:8], P0.5=[11:10],
    // во всех — значение 2 = SPI0.
    GPIO_REG_CFG(K530_GPIO0_BASE) = (GPIO_REG_CFG(K530_GPIO0_BASE) & ~(3u << 4))  | (2u << 4);
    GPIO_REG_CFG(K530_GPIO0_BASE) = (GPIO_REG_CFG(K530_GPIO0_BASE) & ~(3u << 6))  | (2u << 6);
    GPIO_REG_CFG(K530_GPIO0_BASE) = (GPIO_REG_CFG(K530_GPIO0_BASE) & ~(3u << 8))  | (2u << 8);
    GPIO_REG_CFG(K530_GPIO0_BASE) = (GPIO_REG_CFG(K530_GPIO0_BASE) & ~(3u << 10)) | (2u << 10);

    // Сразу следом в оригинале идёт настройка P0.1 (наш строб) как выхода —
    // MODE.бит1 = 1 (P0.1 остаётся ОБЫЧНЫМ GPIO, просто как output). Это
    // закрывает старый TODO про направление пина строба из раздела 2.
    GPIO_REG_MODE(K530_GPIO0_BASE) = (GPIO_REG_MODE(K530_GPIO0_BASE) & ~(1u << K530_BT_READY_PIN))
                                       | (1u << K530_BT_READY_PIN);
}

// TODO(HIGH PRIORITY, всё ещё не подтверждено): регистры конфигурации режима
// SPI0 (CTRL0/CTRL1/CLKDIV или аналог), включение тактирования периферии
// (AHBCLKEN/аналог), настройка пинов P0.2-P0.5 под альтернативную функцию
// SPI0 (а не GPIO). Без этого блока прерывание SPI0_IRQn просто не придёт.
static void k530_spi0_hw_init(void) {
    // TODO/CONFIRM: точный порядок вызовов при ХОЛОДНОМ старте (после reset)
    // не был найден в этой сессии — мы уверенно подтвердили только порядок
    // "disable -> reinit" в рамках ОДНОЙ SPI0-транзакции внутри ISR (см. ниже).
    // Здесь используем ту же связку как разумное предположение для первичной
    // инициализации; если на реальном железе SPI0 не заработает с первого
    // кадра — начните проверку именно с этого места.
    k530_spi0_pins_to_alt_function();
    k530_spi0_clock_and_basic_enable();
    k530_spi0_reinit();
}

static bool k530_spi0_slave_ready = false;

// ----------------------------------------------------------------------
// TX-буфер, который ISR отдаёт мастеру по запросу (аналог RAM 0x20000B34
// в оригинальной прошивке). Обновляется из bluetooth_send_keyboard().
// volatile — пишется из основного потока, читается из ISR.
// ----------------------------------------------------------------------
static volatile uint8_t k530_tx_frame[K530_FRAME_LEN];

// Состояние приёмника (аналог 0x200000B3/B4/B5/C8 из оригинала)
// ----------------------------------------------------------------------
// НОВАЯ МОДЕЛЬ СИНХРОНИЗАЦИИ RX (заменяет старую "первый байт после
// простоя = команда"). Причина замены: реальные аппаратные тесты
// показали, что между логическими 21-байтными кадрами от мастера
// проходит переменное количество холостых байт (наблюдалось ~1 байт
// 0xA2 + ~17 нулевых байт) — граница кадра НЕ совпадает с моментами,
// когда наш software emerges из состояния "простой". SELDIS (CTRL0
// бит18, Auto-SEL) проверен дословно в коде — уже включён во всех
// прошлых тестах, проблему не решает (вероятно, относится только к
// master-режиму генерации CS, не применимо к нашему slave-режиму).
//
// Вместо этого — скользящее окно из последних 21 принятых байт с
// НЕПРЕРЫВНОЙ проверкой чек-суммы НА КАЖДОМ байте, независимо от того,
// в каком состоянии мы считаем себя находящимися. Как только сумма
// последних 20 байт в окне (mod 256) совпадает с 21-м (самым новым)
// байтом — это ПОДТВЕРЖДЁННАЯ (с точностью ~1/256 ложного срабатывания)
// граница конца кадра, а не просто наше предположение. Метод устойчив к
// ЛЮБОМУ количеству и содержимому холостых байт между кадрами, поскольку
// не полагается на то, "когда мы сами были готовы начать слушать".
static uint8_t  k530_sync_ring[K530_FRAME_LEN]; // последние 21 принятых байта, по кругу
static uint8_t  k530_sync_ring_pos = 0;          // куда положить СЛЕДУЮЩИЙ байт
static uint16_t k530_sync_ring_sum = 0;           // сумма ВСЕХ 21 байт в кольце сейчас

// Ответная часть (что мы шлём в SPI0_REG_DATA) сохранена по структуре из
// старой версии (диспетчер по k530_txn_cmd: 0x20=loopback, 0xA2=эхо
// TXBUF, иначе 0) — эта логика не была под подозрением, менялось только
// то, КОГДА мы считаем текущий байт "командой" нового кадра.
static volatile uint8_t k530_resp_count       = 0;  // счётчик байт ответа с начала текущего кадра
static volatile uint8_t k530_txn_cmd          = 0;  // команда текущего кадра (валиден только когда !k530_expect_cmd_next)
static volatile bool    k530_expect_cmd_next  = true; // следующий байт — команда НОВОГО кадра
                                                          // (изначально true: до первой найденной
                                                          // по чек-сумме границы честно не знаем,
                                                          // где начало, поэтому отвечаем нулями,
                                                          // пока не найдём первую границу)

static void k530_spi0_load_tx_buffer(const uint8_t *frame, uint8_t len) {
    // Просто копируем в volatile-буфер, который читает ISR. Критическая
    // секция не показана явно — на реальном ChibiOS оберните это
    // chSysLock()/chSysUnlock() или аналогом отключения SPI0_IRQn на время
    // копирования, чтобы избежать гонки, если импульс P0.1 может прийти
    // "слишком быстро" относительно этой записи (маловероятно по таймингам,
    // но не проверено).
    if (len > K530_FRAME_LEN) len = K530_FRAME_LEN;
    memcpy((void *)k530_tx_frame, frame, len);
}

