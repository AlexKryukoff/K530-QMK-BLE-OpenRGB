// 2. АППАРАТНЫЙ УРОВЕНЬ — GPIO (подтверждено реверс-инжинирингом)
// ============================================================================
// Базовые адреса GPIO-портов подтверждены через официальный CMSIS-заголовок
// SONiX (SN32F260.h, близкий родственник SN32F248B) — раунд 6 отчёта.
// Смещения BSET(+0x24)/BCLR(+0x28) совпали дословно между RE и даташитом.

#define K530_GPIO0_BASE 0x40044000u  // "порт P0" — сюда подключены линии BT-модуля
#define K530_GPIO1_BASE 0x40046000u  // порт P1 — физический тумблер BT on/off (бит 13), возможно mode-бит (бит14)

#define GPIO_REG_DATA(base)  (*(volatile uint32_t *)((base) + 0x00))
#define GPIO_REG_MODE(base)  (*(volatile uint32_t *)((base) + 0x04))
#define GPIO_REG_BSET(base)  (*(volatile uint32_t *)((base) + 0x24))
#define GPIO_REG_BCLR(base)  (*(volatile uint32_t *)((base) + 0x28))

// P0.1 — строб "данные готовы" для BT-чипа (GPIO6 модуля PAR2801, судя по RE).
// TODO/CONFIRM: перепроверьте реальный номер пина на вашей плате мультиметром/
// логическим анализатором, прежде чем полагаться на это значение как на истину.
#define K530_BT_READY_PIN 1u

static inline void k530_gpio_set(uint32_t base, uint8_t pin) {
    GPIO_REG_BSET(base) = (1u << pin);
}
static inline void k530_gpio_clear(uint32_t base, uint8_t pin) {
    GPIO_REG_BCLR(base) = (1u << pin);
}

// Импульс "данные готовы": SET -> delay -> CLEAR.
// В оригинальной прошивке — delay(10) условных единиц её собственной функции
// задержки (адрес 0x244 в дампе), пересчёт в микросекунды НЕ подтверждён.
// TODO/CONFIRM: подберите реальную длительность по логическому анализатору;
// 10us — осторожная стартовая догадка, не проверенная эмпирически.
#define K530_BT_STROBE_DELAY_US 10u

static void k530_bt_pulse_ready(void) {
    k530_gpio_set(K530_GPIO0_BASE, K530_BT_READY_PIN);
    wait_us(K530_BT_STROBE_DELAY_US);
    k530_gpio_clear(K530_GPIO0_BASE, K530_BT_READY_PIN);
}

