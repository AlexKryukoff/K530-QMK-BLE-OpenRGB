// 5Б. ОТЛАДКА НА РЕАЛЬНОМ ЖЕЛЕЗЕ БЕЗ ЛОГИЧЕСКОГО АНАЛИЗАТОРА
// ============================================================================
// Печать прямо из k530_spi0_isr() НЕ ДЕЛАЕМ — прерывание должно быть быстрым
// (мастер клокует байты с фиксированным таймингом, задержка в обработчике
// может привести к рассинхронизации побайтового обмена). Вместо этого ISR
// только копирует нужные данные в простую volatile-структуру-снимок, а сама
// печать (uprintf/dprintf) происходит из bluetooth_task(), которая
// вызывается из основного цикла QMK, не из прерывания.
//
// Использование: добавьте в rules.mk ��ашей клавиатуры
//     CONSOLE_ENABLE = yes
//     OPT_DEFS += -DK530_BT_DEBUG
// и смотрите вывод через `qmk console` (или hid_listen/QMK Toolbox).
//
// ПОРЯДОК BRING-UP (делайте по шагам, не всё сразу — каждый следующий шаг
// имеет смысл проверять только если предыдущий подтвердился):
//
//   Шаг 1. Смотрите ТОЛЬКО k530_debug.irq_count. Включите клавиатуру в
//          режим BT (тумблер) и следите, растёт ли счётчик вообще.
//          Если НЕ растёт — проблема на уровне физики/настройки периферии
//          (пины P0.2-P0.5 не переключились в альтернативную функцию,
//          NVIC IRQ6 не разрешён, тактирование SPI0 не включено, или сам
//          тум��ле�� BT on/off не ��итается верно, см. k530_bt_enabled_stable)
//          — смысла проверять что-либо дальше нет, пока это не растёт.
//   Шаг 2. Если растёт — смотрите last_txn_cmd (первый байт транзакции).
//          Ожидаем увидеть 0xA2 (см. отчёт, раунд 9-10) — если приходит
//          что-то другое или "мусор" — п��от��к��л/тайминги SPI отличаются
//          от предположенных, нужно разбираться отдельно.
//   Шаг 3. Смотрите last_rx_frame (21 байт) и last_checksum_ok — сверяйте
//          с ожидаемой структурой кадра (см. раздел 4).
//   Шаг 4. Только после того, как шаги 1-3 подтвердились — проверяйте,
//          доходит ли реальный HID-ввод (нажатие клавиши) до хоста по BT.
// ----------------------------------------------------------------------

typedef struct {
    volatile uint32_t irq_count;         // Шаг 1: растёт ли вообще при входе в ISR
    volatile uint8_t  last_txn_cmd;       // Шаг 2: первый байт последней транзакции
    // Достаточно первых 8 байт: функционально нужны только [4] (link) и [7]
    // (battery); полный снимок кадра нужен был только под отладочную печать.
    // Урезано с K530_RX_FRAME_LEN до 8 ради экономии RAM (совместная сборка с OpenRGB).
    volatile uint8_t  last_rx_frame[8];                 // Шаг 3: снимок начала принятого кадра
    volatile uint8_t  last_rx_frame_len;                // фактическая длина кадра (переменная)
    volatile bool      last_checksum_ok;   // Шаг 3: результат проверки чек-суммы
    volatile bool      frame_ready;         // флаг "есть новые данные для печати" — ISR
                                              // выставляет, bluetooth_task() читает и сбрасывает

    // --- Тайминг disable()+reinit() (исследование медленного reinit;
    // ГИПОТЕЗА ЗАКРЫТА — эмпирически подтверждено 0 тиков SysTick, оставлено
    // для справки/на случай повторной проверки после других изменений) ---
    volatile uint32_t reinit_ticks;            // длительность в тиках SysTick (см. ISR)
    volatile bool     reinit_report_pending;
} k530_debug_snapshot_t;

static k530_debug_snapshot_t k530_debug = {0};

// ----------------------------------------------------------------------
// ДИАГНОСТИКА (новый раунд): сырой поток принятых байт БЕЗ нашей
// собственной 21-байтной группировки.
// ----------------------------------------------------------------------
// Обе предыдущие гипотезы (медленный reinit, RXTOIF-как-триггер)
// эмпирически закрыты. Следующая проверяемая идея: паттерн
// "A7 00 00 00 02 FF 00 64", который дрейфует внутри наших 21-байтных
// окон, может дрейфовать именно ПОТОМУ, что реальная структура потока от
// мастера вообще не привязана к 21 байту — а мы искусственно режем
// непрерывный (или иначе устроенный) поток на кадры по 21 байту чисто
// программным счётчиком, что и создаёт иллюзию "дрейфа" там, где на самом
// деле просто другая, ещё не понятая структура. Этот лог обходит проблему
// полностью: каждый байт, реально прочитанный из SPI0_REG_DATA, попадает
// сюда СРАЗУ, без интерпретации "какой это байт кадра" — можно будет
// увидеть настоящий период повторения глазами по печати.
#ifdef K530_BT_DEBUG
#define K530_RAW_LOG_SIZE 64
static volatile uint8_t  k530_raw_log[K530_RAW_LOG_SIZE];
static volatile uint8_t  k530_raw_log_count = 0;
static volatile bool     k530_raw_log_ready = false;

static inline void k530_raw_log_push(uint8_t b) {
    if (k530_raw_log_count < K530_RAW_LOG_SIZE) {
        k530_raw_log[k530_raw_log_count] = b;
        k530_raw_log_count++;
    }
    if (k530_raw_log_count >= K530_RAW_LOG_SIZE) {
        k530_raw_log_ready = true; // печать и сброс — в bluetooth_task(), не в ISR
    }
}
#endif

