void bluetooth_init(void) {
    k530_gpio_hw_init();

    // Первичный опрос тумблеров ДО включения SPI0 — чтобы не включать
    // транспорт впустую, если BT физически выключен тумблером.
    k530_poll_bt_toggle();
    k530_poll_host_slot();

    // Start SPI0 in BOTH states. Even when the toggle is OFF at cold boot the
    // BT module powers up and auto-advertises/connects on its own. If SPI0 is
    // not started we never see that (RX silent, last_rx_frame stays 0x00) and
    // never send a disconnect -> keyboard connects while OFF until a manual
    // toggle. So bring SPI0 up regardless, and when OFF send an initial
    // disconnect. The OFF-hold gate in bluetooth_task() then keeps re-sending
    // (A7[4]!=0x00) until the module is actually knocked down.
    k530_spi0_hw_init();
    k530_spi0_slave_ready = true;
    if (!k530_bt_enabled_stable) {
        k530_send_bt_control(false);   /* knock down module that auto-connected at power-up */
#ifdef K530_BT_DEBUG
        dprintf("[K530_BT] BT toggle OFF at init: SPI0 started, initial disconnect sent\n");
#endif
    }

    // Направление и функция P0.1 (��аш строб) теперь настраиваются внутри
    // k530_spi0_pins_to_alt_function(), которая вызывается из
    // k530_spi0_hw_init() выше (только если BT включен тумблером).

#ifdef K530_BT_DEBUG
    dprintf("[K530_BT] bluetooth_init() called, BT=%s, host_slot=%d\n",
            k530_bt_enabled_stable ? "ON" : "OFF", (int)k530_host_slot_stable);
#endif
}

void bluetooth_task(void) {
    // Периодический опрос обоих тумблеров с debounce (вызывайте эту функцию
    // из главного цикла QMK — например, и�� matrix_scan_user() ��ли housekeeping
    // task с достаточной частотой, чтобы debounce отрабатывал корректно;
    // оригинал опрашивает это как часть основного цикла сканирования матрицы,
    // см. отчёт, раунд 6).
    bool bt_changed   = k530_poll_bt_toggle();
    bool host_changed = k530_poll_host_slot(); // TODO: пока результат явно не используется ниже,
                             // кроме хранения в k530_host_slot_stable — если
                             // нужно программно ��ередавать номер ��лота в
                             // TX[1]/TX[2] кадра, самое время сделать это тут.

    if (bt_changed) {
        if (k530_bt_enabled_stable) {
            // Тумблер только что переключили в положение "BT ON":
            k530_spi0_hw_init();
            k530_spi0_slave_ready = true;
            // Выбор активного хоста (0xA6) — ВРЕМЕННО ОТКЛЮЧЕНО, сначала
            // добиваем ON/OFF (см. k530_bt_host_switch_enabled).
            if (k530_bt_host_switch_enabled) {
                k530_send_bt_host_switch();
            }
            // Сообщаем модулю: линк ВКЛ (0xA5, byte[7]=0x01), чтобы он снова
            // начал рекламу после предыдущего OFF.
            k530_send_bt_control(true);
#ifdef K530_BT_DEBUG
            dprintf("[K530_BT] BT toggle -> ON, SPI0 (re)started + link-enable frame sent\n");
#endif
        } else {
            // Тумблер только что переключили в положение "BT OFF":
            // ИСПРАВЛЕНО: не глушим SPI0 сразу. Сначала передаём модулю
            // команду выключения линка (0xA5, byte[7]=0x02) — иначе модуль
            // остаётся активным и про��олжает рекламу (лог: A7-кадры
            // идут даже при OFF). SPI0 держим живым, чтобы модуль
            // успел опросить кадр и разорвать соединение.
            // ИСПРАВЛЕНО (реверс стока): реальное выключение — команда 0xAA,
            // а НЕ 0xA5. 0xA5/byte[7]=0x01 в стоке = реконнект (модуль вещает).
            // Держим SPI0 ЖИВЫМ и шлём модулю команду 0x00 (стоп рекламы).
            k530_spi0_hw_init();
            k530_spi0_slave_ready = true;
            // STOCK: OFF = valid 0xA5 frame with BB=1 (reconnect/silent) -> module
            // stops advertising draconic-N. There is NO 0x00 stop opcode in stock.
            k530_send_bt_control(false);
#ifdef K530_BT_DEBUG
            dprintf("[K530_BT] BT toggle -> OFF, reconnect frame (BB=1) sent, SPI0 kept alive\n");
#endif
        }
    } else if (host_changed && k530_bt_enabled_stable) {
        // Селектор хоста (P0.6/P0.7) сменился при включённом BT: пере-
        // рекламируемся на новом канале. Раньше кадр слался ТОЛЬКО по ON/OFF,
        // поэтому модуль не узнавал о смене хоста и имя в эфире не менялось.
        if (k530_bt_host_switch_enabled) {
            // STOCK-FAITHFUL (0x56D6): on a SETTLED selector change just send
            // ONE 0xA6 host switch -- no disconnect, no wait, no OFF/ON cycle,
            // and NO trailing 0xA5 (a trailing advertise could bounce the module
            // back to the previous host). The settle-debounce above guarantees
            // this is the FINAL resting slot, so we fire exactly once.
            k530_send_bt_host_switch();             // 0xA6 primer + frame -> draconic-N
            k530_led_host_indicator_set(k530_host_slot_stable);  // stub: host-slot LED
#ifdef K530_BT_DEBUG
            dprintf("[K530_BT] host slot changed -> 0xA6 host-switch, slot=%d\n",
                    (int)k530_host_slot_stable);
#endif
        }
    }
    // OFF hold: модуль сам возобновляет рекламу, поэтому пока тумблер в OFF —
    // периодически пере-отправляем 0x00 по живому линку.
    if (!k530_bt_enabled_stable) {
        // OFF hold: re-send disconnect ONLY while the module still reports it
        // is up (A7 status byte[4] != 0x00). Once it is down (0x00) we STOP, so
        // there is no continuous frame spam / chip load while OFF. Stock is
        // event-driven and does not spam either; this matches that intent but
        // still re-kicks if the module tries to re-advertise on its own
        // (observed ~12x per OFF window in the logs). Mirrors the ON retry.
        static uint16_t k530_off_stop_ctr = 0;
        if (k530_debug.last_rx_frame[4] != 0x00u) {
            if (++k530_off_stop_ctr >= K530_BT_OFF_STOP_PERIOD) {
                k530_off_stop_ctr = 0;
                k530_send_bt_control(false);   /* knock module back down if it came up */
            }
        } else {
            k530_off_stop_ctr = 0;   /* already down -> stop sending, no spam */
        }
    } else {
        // ON cold-start fix: at cold boot the BT module can miss the single
        // advertise frame (it is still initializing) and the link never comes
        // up until the toggle is cycled by hand. While the module reports idle
        // (A7 status byte[4] == 0x00), periodically re-send advertise. Once it
        // comes up (0x02 advertising / 0x03 connected) we STOP, so an active
        // link is never disturbed. (Mirrors the OFF-hold re-send above.)
        static uint16_t k530_on_adv_ctr = 0;
        if (k530_debug.last_rx_frame[4] == 0x00u) {
            if (++k530_on_adv_ctr >= K530_BT_OFF_STOP_PERIOD) {
                k530_on_adv_ctr = 0;
                k530_send_bt_control(true);   /* re-advertise until module comes up */
            }
        } else {
            k530_on_adv_ctr = 0;   /* module is up -> stop retrying */
        }
    }

    // TODO: если потребуется periodic keep-alive (в оригинале — периодическая
    // отправка "пустого" кадра при mode==2, см. отчёт раунд 4, адрес 0x859A) —
    // реализовать здесь. Пока не реализовано (не критично для первого теста
    // "работают ли вообще нажатия клавиш").

// --- Индикаторные светодиоды у тумблера (заглушки) ---
    k530_led_host_indicator_set(k530_host_slot_stable);
    k530_led_battery_indicator_set(k530_debug.last_rx_frame[7]);  /* TODO/CONFIRM: battery byte index in A7 frame */

    #ifdef K530_BT_DEBUG
    k530_debug_task_print();
    {
        static uint32_t last_irq_snapshot = 0;
        uint32_t cur = k530_debug.irq_count;
        if (cur != last_irq_snapshot) {
            last_irq_snapshot = cur;
            uint8_t snap[32];
            for (uint8_t i = 0; i < 32; i++) {
                snap[i] = k530_sync_ring[(k530_sync_ring_pos + K530_RX_FRAME_LEN - 32 + i) % K530_RX_FRAME_LEN];
            }
            dprintf("[K530_BT] WINDOW32: ");
            for (uint8_t i = 0; i < 32; i++) dprintf("%02X ", snap[i]);
            dprintf("\n");
            int8_t a7 = -1;
            for (uint8_t i = 0; i < 32; i++) { if (snap[i] == 0xA7u) { a7 = (int8_t)i; break; } }
            if (a7 >= 0) {
                uint8_t blk[48]; uint8_t bl = 0;
                for (uint8_t i = (uint8_t)a7; i < 48 && i < 32; i++) {
                    blk[bl++] = snap[i];
                    if (snap[i] == 0x0Cu && i > (uint8_t)a7) break;
                }
                dprintf("[K530_BT] TASK A7..0C len=%u: ", (unsigned)bl);
                for (uint8_t i = 0; i < bl; i++) dprintf("%02X ", blk[i]);
                dprintf("\n");
            }
        }
    }
#endif
}

void bluetooth_send_keyboard(report_keyboard_t *report) {
    if (report == NULL) {
        return;
    }

    if (!k530_bt_enabled_stable) {
        // Тумблер физически выключен — не пытаемся ничего слат��.
        return;
    }

    uint8_t frame[K530_FRAME_LEN];
    k530_build_keyboard_frame(report, frame);

    K530_BT_LOG_FRAME("TX keyboard frame", frame, K530_FRAME_LEN);

    if (!k530_spi0_slave_ready) {
        // SPI0 ещё не реализован по-настоящему — см. TODO в разделе 3.
        // Отладочный вывод кадра при этом всё равно сработает (полезно для
        // первичной сверки формата кадра ДО того, как заработает реальная
        // передача — например, можно временно вручную бит-банговать эти же
        // 21 байт через обычный GPIO для первого теста на логическом
        // анализаторе, не дожидаясь готового SPI0-драйвера).
#ifdef K530_BT_DEBUG
        dprintf("[K530_BT] WARNING: SPI0 not initialized, frame built but NOT sent\n");
#endif
        return;
    }

    k530_spi0_load_tx_buffer(frame, K530_FRAME_LEN);
    k530_bt_pulse_ready();
}

