/*
 * bluetooth.h — публичный интерфейс к драйверу bluetooth.c для K530.
 *
 * bluetooth.c компилируется отдельной единицей трансляции (см. SRC += в
 * rules.mk), поэтому эти четыре функции — единственное, что видно снаружи.
 * Всё остальное (регистры SPI0/GPIO, состояние тумблеров, ISR) остаётся
 * static внутри bluetooth.c, инкапсуляция не нарушается.
 */
#pragma once

#include <stdint.h>
#include <stdbool.h>
#include "report.h" // report_keyboard_t

// Вызвать один раз при старте прошивки (из keyboard_post_init_user()).
void bluetooth_init(void);

// Вызывать периодически из главного цикла (из matrix_scan_user()) —
// опрашивает оба тумблера с debounce, включает/выключает SPI0-транспорт
// при смене положения тумблера BT on/off.
void bluetooth_task(void);

// Отправить текущий 6-key HID-отчёт по Bluetooth (если физически включено
// тумблером; если выключено — функция сама тихо ничего не делает).
void bluetooth_send_keyboard(report_keyboard_t *report);

// Геттеры для интеграции с keymap.c (например, для RGB-индикации режима
// BT/USB или для отладочного вывода в консоль).
bool k530_bluetooth_is_enabled(void);
uint8_t k530_bluetooth_host_slot(void); // 0=неизвестно, 1/2/3=слот
uint8_t k530_bluetooth_link_state(void); // A7[4]: 00 idle/01 bonded/02 adv/03 connected

// ============================================================================
// СОСТОЯНИЕ БАТАРЕИ (реверс стока: функция 0x65C0, LED-индекс 0x6C)
// ============================================================================
// ВАЖНО: модуль НЕ присылает проценты заряда. Стоковый парсер A7-кадра
// (дизасм 0x9DCA..0x9DF2) читает из кадра ровно три байта: [3] (HID-LED
// от хоста), [4] (состояние линка) и [5] (грубый УРОВЕНЬ батареи).
// Байт [7] во всей стоковой прошивке не читается нигде — то, что в логах
// выглядело как "0x64 = 100 %", оказалось константой в кадре (именно
// поэтому индикатор горел зелёным бесконечно). Геттер на байт [7]
// (прежний k530_bluetooth_battery) удалён как нерабочий.
//
// ╔══════════════════════════════════════════════════════════════════════╗
// ║ ЕСЛИ НИЗКИЙ И КРИТИЧЕСКИЙ ЗАРЯД ОТОБРАЖАЮТСЯ НАОБОРОТ —          ║
// ║ ПОМЕНЯЙТЕ МЕСТАМИ ЗНАЧЕНИЯ ДВУХ СЛЕДУЮЩИХ КОНСТАНТ (и всё).   ║
// ║ Больше нигде в коде сырые байты 0x01/0x02 для батареи не встречаются. ║
// ║ Причина: в стоке оба значения дают одинаковый красный, так что     ║
// ║ отличить "низкий" от "критического" по дизасму невозможно —       ║
// ║ порядок ниже взят по порядку проверок в стоке и НЕ проверен       ║
// ║ на живой разряженной батарее.                                       ║
// ╚══════════════════════════════════════════════════════════════════════╝
#define K530_BATT_LOW   0x01u   // низкий заряд        <-- ПОМЕНЯТЬ МЕСТАМИ СО СТРОКОЙ НИЖЕ,
#define K530_BATT_CRIT  0x02u   // критический заряд   <-- если поведение окажется зеркальным
#define K530_BATT_FULL  0xF0u   // полный заряд / "заряжен" (подтверждено на железе)
// Любое другое значение (обычно 0x00) = нормальный заряд.

// Сырой уровень батареи — байт [5] последнего ВАЛИДНОГО A7-кадра.
// Сравнивать с K530_BATT_FULL / K530_BATT_LOW / K530_BATT_CRIT выше.
uint8_t k530_bluetooth_battery_level(void);

// Зарядка подключена — локальный пин MCU P1.14 (GPIO1 DATA, бит 14).
// Этот же бит в стоке гейтит ветку "зелёный vs красный" в батарейной
// функции 0x65C0 и попадает в байт mode исходящих кадров.
// TODO/CONFIRM: трактовка "бит1 == зарядка подключена" — вывод из
// структуры стокового кода + совпадение с наблюдаемым поведением стока
// (заряжается -> зелёный мигает, заряжен -> зелёный ровно). Проверяется
// втыканием/вытыканием кабеля и просмотром бита в логе.
bool k530_bluetooth_is_charging(void);

// true = есть СВЕЖИЕ валидные данные статуса от модуля (пришёл A7-кадр
// с верной чек-суммой не позже K530_A7_STALE_MS назад). Нужно, чтобы не
// врать цветом индикатора, когда модуль молчит.
bool k530_bluetooth_status_valid(void);

// Сброс сопряжения / режим повторной привязки (Fn2+ESC, удержание 3 сек):
// разрывает линк с текущим хостом и снова начинает рекламироваться, чтобы
// подключился новый девайс (реализовано подтверждёнными A5 disconnect+advertise;
// см. подробности в bluetooth.c, раздел 4В). Тихо ничего не делает, если BT
// выключен тумблером или SPI0 не готов.
void k530_send_bt_unpair(void);
